local function rejects(label, mutate, restore)
    local expected = player.parameter_inputs();
    local saved = player.accept_parameters(expected, values, 42);
    mutate();
    expect(label .. ' invalidates a saved snapshot', player.parameters_valid(saved), false);
    local accepted, why = player.accept_parameters(expected, values, 43);
    expect(label .. ' rejects a pending reply', accepted, nil);
    check(label .. ' explains the rejection', type(why) == 'string' and why:find('Check again', 1, true));
    restore();
end
