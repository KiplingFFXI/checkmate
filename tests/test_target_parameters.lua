local function checked(index, reply)
    index, reply = index or 1, reply or values;
    token = token + 1;
    local target_id = MOCK.mob_id(900, index);
    target.on_check(index, target_id, 39, 4, 2, nil, false, token, 'waiting');
    local accepted = player.accept_parameters(player.parameter_inputs(), reply, MOCK.now);
    target.on_parameters(index, target_id, token, accepted);
    return accepted, token;
end
